function pureChinese(value: string) {
  return termPairs.reduce((text, [english, chinese]) => text.replaceAll(english, chinese), value);
}

function hybridChinese(value: string) {
  return termPairs.reduce((text, [english, chinese]) => text.replaceAll(chinese, english), value);
}

const variants = new Map<string, Entry>();
for (const entry of entries) {
  for (const value of [entry.source, entry.en, entry.zh, entry.hybrid, pureChinese(entry.source), hybridChinese(entry.source)]) {
    if (value) variants.set(value.replace(/\s+/g, " ").trim(), entry);
  }
}

export function translateSystemText(value: string, mode: LanguageMode): string {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const core = value.trim();
  if (!core) return value;
  const counted = /^(.*?)[（(](\d+)[）)]$/.exec(core);
  if (counted) {
    const translatedLabel = translateSystemText(counted[1]!, mode);
    if (translatedLabel !== counted[1]) return `${leading}${translatedLabel.trim()} (${counted[2]})${trailing}`;
  }
  const punctuation = /^(.*?)([:：])$/.exec(core);
  if (punctuation) {
    const translatedLabel = translateSystemText(punctuation[1]!, mode);
    if (translatedLabel !== punctuation[1]) return `${leading}${translatedLabel.trim()}${mode === "en" ? ":" : "："}${trailing}`;
  }
  const entry = variants.get(core.replace(/\s+/g, " "));
  if (!entry) return value;
  const translated = mode === "en"
    ? entry.en
    : mode === "zh-terms-en"
      ? entry.hybrid ?? hybridChinese(entry.source)
      : entry.zh ?? pureChinese(entry.source);
  return `${leading}${translated}${trailing}`;
}

export function catalogIntegrityIssues() {
  const issues: string[] = [];
  const sources = new Set<string>();
  for (const entry of entries) {
    if (!entry.source.trim() || !entry.en.trim()) issues.push("Catalog entries must have source and English text");
    if (sources.has(entry.source)) issues.push(`Duplicate source: ${entry.source}`);
    sources.add(entry.source);
  }
  return issues;
}
